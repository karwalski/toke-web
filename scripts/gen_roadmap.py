def esc_none(text):
    """Content in roadmap.json is authored as trusted HTML fragments."""
    return text


def render_stage(st):
    cls = STATUS_CLASS[st["status"]]
    out = [f'  <div class="stage {cls}" id="{st["id"]}">']
    out.append('    <div class="stage-head">')
    out.append(f'      <span class="stage-label">{st["label"]}</span>')
    out.append(f'      <span class="badge">{STATUS_LABEL[st["status"]]}</span>')
    out.append(f'      <span class="stage-date">{st["date"]}</span>')
    out.append("    </div>")
    out.append(f'    <h3>{st["title"]}</h3>')
    out.append(f'    <p>{st["summary"]}</p>')
    if st.get("results"):
        out.append("    <ul>")
        for r in st["results"]:
            out.append(f"      <li>{r}</li>")
        out.append("    </ul>")
    if st.get("caveat"):
        out.append(f'    <p class="caveat"><strong>Caveat.</strong> {st["caveat"]}</p>')
    out.append("  </div>")
    return "\n".join(out)


def render_bench(b):
    out = ['  <div class="bench">']
    out.append('    <div class="bench-head">')
    out.append(f'      <span class="bench-id">{b["id"]}</span>')
    out.append(f'      <span class="bench-name">{b["name"]}</span>')
    out.append(f'      <span class="bench-applies">{b["applies_to"]}</span>')
    out.append("    </div>")
    out.append(f'    <p><span class="k">Measures</span><br>{b["measures"]}</p>')
    out.append(f'    <p><span class="k">Why it is the benchmark</span><br>{b["why"]}</p>')
    if b.get("veto"):
        out.append(f'    <p class="veto"><strong>The veto:</strong> {b["veto"]}</p>')
    out.append("  </div>")
    return "\n".join(out)



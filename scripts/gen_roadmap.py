def splice(text, block):
    if BEGIN not in text or END not in text:
        raise SystemExit(
            "templates/index.tkt has no ROADMAP:BEGIN/ROADMAP:END markers -- "
            "add them around the milestones block first."
        )
    head = text[: text.index(BEGIN)]
    tail = text[text.index(END) + len(END):]
    return head + block + tail


def main():
    check = "--check" in sys.argv
    d = json.loads(SRC.read_text(encoding="utf-8"))

    page = render_roadmap_page(d)
    index_text = INDEX_TPL.read_text(encoding="utf-8")
    new_index = splice(index_text, render_index_block(d))

    stale = []
    if not ROADMAP_TPL.exists() or ROADMAP_TPL.read_text(encoding="utf-8") != page:
        stale.append(str(ROADMAP_TPL.relative_to(ROOT)))
    if index_text != new_index:
        stale.append(str(INDEX_TPL.relative_to(ROOT)))

    if check:
        if stale:
            print("STALE (run: python3 scripts/gen_roadmap.py):")
            for s in stale:
                print("  " + s)
            return 1
        print("roadmap: templates/roadmap.tkt and templates/index.tkt are in sync with content/roadmap.json")
        return 0

    ROADMAP_TPL.write_text(page, encoding="utf-8")
    INDEX_TPL.write_text(new_index, encoding="utf-8")
    print("wrote templates/roadmap.tkt (%d stages, %d benchmarks)" % (len(d["stages"]), len(d["benchmarks"])))
    print("wrote templates/index.tkt ROADMAP:BEGIN/END block")
    return 0


if __name__ == "__main__":
    sys.exit(main())
